function schema(value, key = '') {
  const description = descriptions[key] || `${scopes[key.split('.')[0]] || 'Theme'}: ${key}. See the configuration guide for behavior.`;
  if (Array.isArray(value)) return { type: 'array', description, default: value, items: { type: 'object' } };
  if (value && typeof value === 'object') return { type: 'object', description, additionalProperties: !Object.keys(value).length, properties: Object.fromEntries(Object.entries(value).map(([name, child]) => [name, schema(child, key ? `${key}.${name}` : name)])) };
  return { type: typeof value, description, default: value };
}

