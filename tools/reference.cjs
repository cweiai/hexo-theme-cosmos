const rows = [];
function walk(value, prefix = '') {
  for (const [key, child] of Object.entries(value)) {
    const name = prefix ? prefix + '.' + key : key;
    if (child && typeof child === 'object' && !Array.isArray(child) && Object.keys(child).length) walk(child, name);
    else {
      const setting = name.split('.').reduce((node, key) => node.properties[key], definition);
      rows.push({ name, child, type: [setting.type].flat().join(' or ') });
    }
  }
}
walk(defaults);
const cell = value => String(value).replace(/\|/g, '\\|').replace(/\n/g, '<br>');
function reference(language) {
  const chinese = language === 'zh-CN';
  const descriptionsForLanguage = chinese ? descriptionsZh : descriptions;
  let result = '';
  for (const [group, scope] of Object.entries(chinese ? scopesZh : scopes)) {
    result += `### ${group} ${chinese ? '默认值' : 'defaults'}\n\n${chinese ? '作用范围' : 'Applies to'}: ${scope}.\n\n${chinese ? '| 配置项 | 类型 | 默认值 | 说明 |' : '| Setting | Type | Default | Notes |'}\n| --- | --- | --- | --- |\n`;
    for (const row of rows.filter(row => row.name === group || row.name.startsWith(group + '.'))) {
      const raw = JSON.stringify(row.child);
      const escaped = raw.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/\|/g, '&#124;');
      const value = raw.length > 140 ? `<details><summary>${chinese ? '查看全部条目' : 'Show all entries'}</summary><code>${escaped}</code></details>` : '`' + cell(raw) + '`';
      const typesZh = { string: '字符串', boolean: '布尔值', number: '数字', integer: '整数', object: '对象', array: '列表', 'number or string': '数字或字符串' };
      result += `| \`${row.name}\` | ${chinese ? typesZh[row.type] : row.type} | ${value} | ${cell(descriptionsForLanguage[row.name] || '')} |\n`;
    }
    result += '\n';
  }
  return result;
}

const guides = ['en', 'zh-CN'].map(language => {
  const name = language === 'en' ? 'configuration.md' : 'configuration.zh-CN.md';
  const guide = normalizeLineEndings(fs.readFileSync(path.join(root, 'docs', name), 'utf8'));
  const marker = /<!-- cosmos:defaults:start -->[\s\S]*?<!-- cosmos:defaults:end -->/;
  if (!marker.test(guide)) throw new Error(`${name} is missing its defaults markers.`);
  return [name, guide.replace(marker, `<!-- cosmos:defaults:start -->\n\n${reference(language)}<!-- cosmos:defaults:end -->`)];
});

try {
  const Ajv = require('ajv');
  const validate = new Ajv({ strict: false }).compile(definition);
  const configs = ['_config.yml', 'examples/_config.cosmos.yml', ...fs.readdirSync(path.join(root, 'presets')).filter(name => name.endsWith('.yml')).map(name => 'presets/' + name)];
  for (const file of configs) {
    if (!validate(yaml.load(fs.readFileSync(path.join(root, file), 'utf8')))) throw new Error(`${file}: ${JSON.stringify(validate.errors)}`);
  }
  for (const [name, value] of [...guides, ['theme.schema.json', JSON.stringify(definition, null, 2) + '\n']]) {
    const target = path.join(root, 'docs', name);
    if (process.argv.includes('--check')) {
      if (!fs.existsSync(target) || normalizeLineEndings(fs.readFileSync(target, 'utf8')) !== value) throw new Error(`${name} is stale. Run npm run docs:reference.`);
    } else fs.writeFileSync(target, value);
  }
  console.log(`[Cosmos] Configuration reference and schema ${process.argv.includes('--check') ? 'are current' : 'generated'}.`);
} catch (error) { console.error(error.message); process.exitCode = 1; }
